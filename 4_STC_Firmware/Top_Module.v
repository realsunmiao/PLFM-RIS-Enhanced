////////////////////////////////////////////////////////////////////////////////
// Module: Top_Module.v
// Description: RIS 雷达系统顶层模块
// 
// 功能集成:
//   1. STC 编码器 (时空编码)
//   2. SPI 通信接口 (与 STM32/上位机通信)
//   3. 控制信号输出 (PIN + VarCap)
//
// 作者: Wukong AI Assistant
// 日期: 2026-08-19
////////////////////////////////////////////////////////////////////////////////

module Top_Module (
    // ========================================================================
    // 时钟与复位
    // ========================================================================
    input wire          clk_100m,       // 100 MHz 系统时钟
    input wire          rst_n,          // 复位信号 (低有效)
    
    // ========================================================================
    // SPI 通信接口 (与 STM32 或 USB-UART 桥接)
    // ========================================================================
    input wire          spi_cs,         // SPI 片选
    input wire          spi_clk,        // SPI 时钟
    input wire          spi_mosi,       // SPI 主出从入
    output wire         spi_miso,       // SPI 主入从出
    
    // ========================================================================
    // RIS 阵列控制输出
    // ========================================================================
    output wire [63:0]  pin_ctrl,       // PIN 二极管控制 (64 路)
    output wire [511:0] varcap_ctrl,    // 变容二极管控制 (64×8-bit)
    
    // ========================================================================
    // 状态指示
    // ========================================================================
    output wire         led_ready,      // 系统就绪指示灯
    output wire         led_active      // 数据传输指示灯
);

// ============================================================================
// 内部信号
// ============================================================================
wire sys_rst_n;                         // 系统复位 (同步后)
wire [15:0] cfg_azimuth;                // 配置的方位角
wire [15:0] cfg_elevation;              // 配置的俯仰角
wire [31:0] cfg_f0;                     // 起始频率
wire [31:0] cfg_k_slope;                // 调频斜率
wire [31:0] cfg_t_period;               // 调频周期
wire cfg_enable;                        // 使能信号

// ============================================================================
// 复位同步器
// ============================================================================
reg [2:0] rst_sync;
always @(posedge clk_100m) begin
    rst_sync <= {rst_sync[1:0], rst_n};
end
assign sys_rst_n = rst_sync[2];

// ============================================================================
// SPI 配置寄存器接口
// ============================================================================
SPI_Interface spi_if (
    .clk        (clk_100m),
    .rst_n      (sys_rst_n),
    .spi_cs     (spi_cs),
    .spi_clk    (spi_clk),
    .spi_mosi   (spi_mosi),
    .spi_miso   (spi_miso),
    
    // 配置输出
    .azimuth    (cfg_azimuth),
    .elevation  (cfg_elevation),
    .f0         (cfg_f0),
    .k_slope    (cfg_k_slope),
    .t_period   (cfg_t_period),
    .enable     (cfg_enable),
    
    // 状态指示
    .led_active (led_active)
);

// ============================================================================
// 时空编码核心
// ============================================================================
STC_Encoder stc_encoder (
    .clk            (clk_100m),
    .rst_n          (sys_rst_n),
    .enable         (cfg_enable),
    
    // 波束指向
    .azimuth_angle  (cfg_azimuth),
    .elevation_angle(cfg_elevation),
    
    // LFM 波形参数
    .f0             (cfg_f0),
    .k_slope        (cfg_k_slope),
    .T_period       (cfg_t_period),
    
    // 控制输出
    .pin_control    (pin_ctrl),
    .varcap_control (varcap_ctrl)
);

// ============================================================================
// 状态指示
// ============================================================================
assign led_ready = sys_rst_n;

// ============================================================================
// 调试信号 (可选, 通过 ILA 观察)
// ============================================================================
`ifdef DEBUG
    wire [31:0] debug_time = stc_encoder.time_counter;
    wire [31:0] debug_freq = stc_encoder.instantaneous_freq;
    
    // ILA 例化 (Xilinx ChipScope)
    // ila_debug ila_inst (
    //     .clk(clk_100m),
    //     .probe0(debug_time),
    //     .probe1(debug_freq)
    // );
`endif

endmodule
